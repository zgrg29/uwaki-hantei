function chinese(text) {
  if (Object.hasOwn(ZH, text)) return ZH[text];
  // Match original text in one pass so translated output is never translated again.
  const keys = Object.keys(ZH).sort((a,b) => b.length-a.length);
  const pattern = new RegExp(keys.map(k => k.replace(/[.*+?^${}()|[\]\\]/g,'\\$&')).join('|'),'g');
  return text.replace(pattern, key => ZH[key]);
}
function tr(text, languages = selectedLanguages) {
  if (languages.length === 2) return chinese(text) === text ? text : chinese(text) + '\n' + text;
  return languages[0] === 'zh' ? chinese(text) : text;
}
const originalText = new WeakMap();
function localize(root) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  for (let node; (node=walker.nextNode());) {
    if (node.parentElement.closest('script,style,textarea,footer,[data-language-controls]')) continue;
    if (!originalText.has(node)) originalText.set(node, node.nodeValue);
    node.nodeValue = tr(originalText.get(node));
  }
  const footer = root.querySelector('footer');
  if (footer) footer.innerHTML = selectedLanguages.map(lang => lang === 'zh'
    ? '<p lang="zh-CN">题目来源：健屋花那（<a href="https://x.com/sukosuko_sukoya/status/2107121927278166034" target="_blank" rel="noopener">原帖</a>）的《这算出轨吗？判定问卷》，本页面据此制作<br>原表设计：ありあ（<a href="https://x.com/air_trpg" target="_blank" rel="noopener">@air_trpg</a>）</p>'
    : '<p lang="ja">出典：健屋花那さん（<a href="https://x.com/sukosuko_sukoya/status/2107121927278166034" target="_blank" rel="noopener">@sukosuko_sukoya のポスト</a>）の「これって浮気？判定シート」をもとに作成しています<br>シートデザイン：ありあさん（<a href="https://x.com/air_trpg" target="_blank" rel="noopener">@air_trpg</a>）</p>').join('');
  root.querySelectorAll('[alt],[aria-label]').forEach(el => {
    if (!el._originalAttrs) el._originalAttrs = {};
    for (const key of ['alt','aria-label']) if (el.hasAttribute(key)) {
      el._originalAttrs[key] ??= el.getAttribute(key);
      el.setAttribute(key,tr(el._originalAttrs[key]));
    }
  });
}
function initLanguages() {
  QUESTIONS.forEach((q,i) => { ZH[q] = ZH_QUESTIONS[i]; });
  const controls = document.createElement('fieldset');
  controls.className = 'languages'; controls.dataset.languageControls = '';
  controls.innerHTML = '<legend>语言 / 言語</legend><label><input type="checkbox" value="zh"> 中文</label><label><input type="checkbox" value="ja"> 日本語</label>';
  document.querySelector('.wrap').prepend(controls);
  function sync() {
    controls.querySelectorAll('input').forEach(input => {
      input.checked = selectedLanguages.includes(input.value);
      input.disabled = input.checked && selectedLanguages.length === 1;
    });
    document.documentElement.lang = selectedLanguages.includes('zh') ? 'zh-CN' : 'ja';
    document.title = tr('これって浮気？判定シート').replace('\n',' / ');
  }
  controls.addEventListener('change',() => {
    selectedLanguages = [...controls.querySelectorAll('input:checked')].map(x => x.value);
    try { localStorage.setItem('uwaki-languages-v1',JSON.stringify(selectedLanguages)); } catch (_) {}
    sync(); render();
  });
  sync();
}

